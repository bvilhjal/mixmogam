"""Bounded algebra replay of phensim-derived actual KVIK block geometries.

No fitting is performed. Projected phenotype work is repeated across models;
the second work type adds reproducible normal noise and is an algebra control,
not an actual late-sweep residual. Original data were generated by phensim.
"""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import sys


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--archive', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--numba-cache', type=Path, required=True)
    a = p.parse_args()
    a.archive, a.out = a.archive.resolve(), a.out.resolve()
    a.out.mkdir(parents=True, exist_ok=False)
    manifest = json.loads((a.archive / 'manifest.json').read_text())
    source = a.archive / 'source'
    for name, expected in manifest['source']['sha256'].items():
        if sha(source / name) != expected:
            raise RuntimeError(f'frozen source mismatch: {name}')
    limits = manifest['local_thread_environments']['4']
    os.environ.update(limits)
    os.environ['NUMBA_CACHE_DIR'] = str(a.numba_cache.resolve())
    sys.path.insert(0, str(source))
    import numpy as np
    from scipy import linalg
    from scipy.linalg.blas import get_blas_funcs
    from threadpoolctl import threadpool_info, threadpool_limits
    from mixmogam.io.plink import read_plink
    from mixmogam._loco import LocoGenotypes
    from mixmogam._vb import _GemmWorkspace
    from mixmogam.lmm import _design_matrix
    import mixmogam
    if not Path(mixmogam.__file__).resolve().is_relative_to(source):
        raise RuntimeError('wrong package import')
    spec = importlib.util.spec_from_file_location('frozen_driver', a.archive / 'kvik_efficiency.py')
    driver = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(driver)
    power = driver.power_state()
    shutil.copy2(__file__, a.out / 'runner.py')
    seed = 2026100322
    records = []

    def compare(x, y):
        d = x.astype(np.float64) - y.astype(np.float64)
        return dict(array_equal=bool(np.array_equal(x,y)), different_elements=int(np.count_nonzero(x != y)),
                    max_absolute_error=float(np.max(np.abs(d))), rms_error=float(np.sqrt(np.mean(d*d))),
                    relative_l2_error=float(np.linalg.norm(d) / np.linalg.norm(y)),
                    allclose_original_tolerance=bool(np.allclose(x,y,rtol=1e-6,atol=1e-8)))

    gemm = get_blas_funcs('gemm', dtype=np.float32)
    with threadpool_limits(limits=1, user_api='blas'):
        for case_i, entry in enumerate(manifest['inputs'], 1):
            driver.power_state()
            for filename, details in entry['files'].items():
                if sha(filename) != details['sha256']:
                    raise RuntimeError(f'input changed: {filename}')
            case = Path(entry['directory'])
            gt = read_plink(str(case.parent / 'geno'), max_variants=2000)
            if gt.n_samples != 50000 or gt.n_variants != 2000 or len(np.unique(gt.chromosome)) != 1:
                raise RuntimeError('unexpected first parent block geometry')
            y = np.loadtxt(case / 'phenotype.txt', usecols=2)
            X = np.loadtxt(case / 'covariates.txt', usecols=(2,3)) if entry['config']['pcs'] else None
            Xd = _design_matrix(X, y.size, add_intercept=True)
            Q = linalg.qr(Xd, mode='economic')[0]
            yp = y - Q @ (Q.T @ y)
            ys = yp / np.sqrt(np.sum(yp**2) / (y.size-Xd.shape[1]))
            # One actual 2,000-marker group is sufficient for the full/tail
            # geometry. The genotype preparation is the frozen n4 path.
            lg = LocoGenotypes(gt, np.zeros(gt.n_variants,dtype=np.int64), Q,
                               block=4096, cache_bytes=0, n_threads=4)
            # Re-create cached parent-block row views (the formal fits cache).
            parent = lg._standardize(np.arange(2000))
            for B, start in ((128,0), (80,1920)):
                Z = parent[start:start+B]
                for P in (6,10):
                    workspace = _GemmWorkspace(50000,P,128,np.dtype(np.float32),None,4)
                    for work_kind in ('projected_phenotype', 'phenotype_plus_algebra_noise'):
                        work = np.repeat(ys[:,None],P,axis=1).astype(np.float32)
                        if work_kind.endswith('algebra_noise'):
                            rng = np.random.default_rng(seed + case_i*100 + B + P)
                            work += rng.standard_normal(work.shape).astype(np.float32)
                        forward_out = np.empty((128,P),dtype=np.float32)[:B]
                        np.matmul(Z,work,out=forward_out)
                        ref = forward_out.copy()
                        oracle = Z.astype(np.float64) @ work.astype(np.float64)
                        # Exact production call, reusable F prefix includes
                        # the 128 leading allocation and contiguous B80 view.
                        alternatives = {
                            'production_scipy_F_prefix': workspace.forward(Z,work,forward_out).copy(),
                            'numpy_F_work': Z @ np.asfortranarray(work),
                            'scipy_F_fresh_output': gemm(1.0,Z.T,np.asfortranarray(work),trans_a=1,
                                c=np.empty((B,P),dtype=np.float32,order='F'),overwrite_c=1),
                        }
                        storage = np.empty((128,P),dtype=np.float32,order='F')
                        view = storage[:B]
                        leading = gemm(1.0,Z.T,np.asfortranarray(work),trans_a=1,c=view,overwrite_c=1)
                        alternatives['scipy_F_128_row_view'] = leading
                        records.append(dict(case_index=case_i,B=B,P=P,work_kind=work_kind,
                            indices=[start,start+B], Z_shape=list(Z.shape),Z_strides=list(Z.strides),
                            work_strides=list(work.strides),numpy_output_strides=list(forward_out.strides),
                            prefix_output_strides=[4,B*4],leading_output_strides=list(leading.strides),
                            leading_view_reused=bool(np.shares_memory(leading,view)),
                            input_sha256={k:hashlib.sha256(v.tobytes()).hexdigest() for k,v in [('Z',Z),('work',work)]},
                            numpy_vs_float64=compare(ref,oracle),
                            alternatives={name:dict(vs_numpy=compare(value,ref),vs_float64=compare(value,oracle))
                                          for name,value in alternatives.items()}))
            del lg, parent, gt
    driver.save_json(a.out / 'records.json',records)
    driver.save_json(a.out / 'provenance.json',dict(scope=__doc__,archive=str(a.archive),source_directory=str(source),
        source_sha256=manifest['source']['sha256'],script_sha256=sha(a.out/'runner.py'),
        input_files=manifest['inputs'],records_sha256=sha(a.out/'records.json'),
        seed=seed,seed_formula='base + case_index*100 + B + P for algebra noise only',
        thread_environment=limits,numba_cache=str(a.numba_cache),power_state=power,threadpools=threadpool_info(),
        numerical_tolerances=dict(rtol=1e-6,atol=1e-8),
        limits='Two cases, first 2000-variant group only, B128 first block and B80 final block; no full fits or late-sweep residual claims. NumPy-F and noncontiguous F-output views are controls, not production routes.'))
    for r in records:
        d=r['alternatives']['production_scipy_F_prefix']['vs_numpy']
        print(json.dumps({k:r[k] for k in ('case_index','B','P','work_kind')} | d),flush=True)


if __name__ == '__main__':
    main()
